from pathlib import Path

from alembic.command import check, upgrade
from alembic.util import AutogenerateDiffsDetected
import psycopg
from pydantic import SecretStr, ValidationError
import pytest
from sqlalchemy import DefaultClause, Engine, event, text
from sqlalchemy.engine import make_url
from sqlalchemy.pool import ConnectionPoolEntry

from app.core.config import DatabaseSettings, get_settings
from app.infrastructure.db.database import get_alembic_config
from app.infrastructure.db.models.example import ExampleModel

MIGRATIONS = str(Path(__file__).resolve().parents[2] / 'migrations')


def test_url_keeps_credentials_out_of_the_url_structure() -> None:
    """Credentials holding URL syntax round-trip instead of reading as host or path."""
    settings = DatabaseSettings(host='db', port=5432, user='svc@ops', password=SecretStr('p@ss/w:rd%40?#'), name='app')

    url = make_url(settings.url.unicode_string())

    assert (url.username, url.password, url.host, url.database) == ('svc@ops', 'p@ss/w:rd%40?#', 'db', 'app')


def test_invalid_host_keeps_the_password_out_of_the_error() -> None:
    """`PostgresDsn.build` reports a rejected value with the whole URL as its input."""
    settings = DatabaseSettings(host='bad host', port=5432, user='svc', password=SecretStr('secret'), name='app')

    with pytest.raises(ValueError) as exc_info:
        settings.url.unicode_string()

    assert 'input_value' not in str(exc_info.value)


def test_missing_variable_keeps_raw_values_out_of_the_error(monkeypatch: pytest.MonkeyPatch) -> None:
    """A startup failure on a missing variable must not print the password it already loaded."""
    monkeypatch.setenv('DATABASE_PASSWORD', 'hunter2')
    monkeypatch.delenv('DATABASE_USER', raising=False)

    with pytest.raises(ValidationError) as exc_info:
        DatabaseSettings(_env_file=None)  # type: ignore[ty:missing-argument]

    assert 'input_value' not in str(exc_info.value)


def test_migrations_connect_with_the_configured_timeout() -> None:
    """Against an unreachable database a migration gives up after the timeout, not psycopg's 130 s default."""
    connect_parameters: list[dict[str, str]] = []

    def record_parameters(dbapi_connection: psycopg.Connection, connection_record: ConnectionPoolEntry) -> None:
        connect_parameters.append(dbapi_connection.info.get_parameters())

    event.listen(Engine, 'connect', record_parameters)
    try:
        upgrade(get_alembic_config(MIGRATIONS), 'head')
    finally:
        event.remove(Engine, 'connect', record_parameters)

    assert connect_parameters[0]['connect_timeout'] == str(get_settings().DATABASE.connect_timeout_seconds)


def test_autogenerate_compares_server_defaults(monkeypatch: pytest.MonkeyPatch) -> None:
    """A model's new server default reaches the next migration."""
    alembic_config = get_alembic_config(MIGRATIONS)
    upgrade(alembic_config, 'head')
    check(alembic_config)  # the migrations match the models
    monkeypatch.setattr(ExampleModel.__table__.c.description, 'server_default', DefaultClause(text("''")))

    with pytest.raises(AutogenerateDiffsDetected):
        check(alembic_config)
